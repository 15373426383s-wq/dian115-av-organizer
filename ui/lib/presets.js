// 番号类型 → 引擎用的来源类型（kinds）。
export function numberKind(parsedKind, number) {
  const value = String(number || '')
  if (parsedKind === 'uncensored-date' || /^\d{6}[-_]\d{2,3}$/.test(value)) {
    if (/^\d{6}-\d{3}$/.test(value)) return 'carib'
    if (/^\d{6}_\d{2}$/.test(value)) return 'musume'
    return 'pondo'
  }
  if (parsedKind === 'dmm') return 'standard'
  if (parsedKind === 'alnum' || parsedKind === 'lettered') return 'standard'
  return parsedKind || 'standard'
}

